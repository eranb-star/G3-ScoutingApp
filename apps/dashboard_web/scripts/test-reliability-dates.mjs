import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),{build}=createRequire(require.resolve('vite'))('esbuild');
const result=await build({stdin:{contents:`export {israelLocalTime,israelTimeToUtc} from './src/lib/attendanceTime';export {sourceRevisionDate} from '../../backend/supabase/functions/onshape-connector/sourceDate';`,resolveDir:process.cwd()},bundle:true,platform:'node',format:'esm',write:false});
const {israelLocalTime,israelTimeToUtc,sourceRevisionDate}=await import('data:text/javascript;base64,'+Buffer.from(result.outputFiles[0].text).toString('base64'));
assert.equal(israelTimeToUtc('2026-10-15T19:30'),'2026-10-15T16:30:00.000Z');
assert.equal(israelTimeToUtc('2026-12-15T19:30'),'2026-12-15T17:30:00.000Z');
assert.equal(israelLocalTime('2026-10-15T16:30:00Z'),'2026-10-15T19:30');
assert.throws(()=>israelTimeToUtc('2026-03-27T02:30'),/ambiguous|does not exist/);
assert.throws(()=>israelTimeToUtc('2026-10-25T01:30'),/ambiguous|does not exist/);
assert.throws(()=>israelTimeToUtc('2026-02-30T19:30'));
assert.throws(()=>israelTimeToUtc('not a date'));
const history=[{microversionId:'other',date:'2026-10-15T10:00:00Z'},{microversionId:'selected',date:'2026-10-01T12:00:00Z'}];
assert.equal(sourceRevisionDate(history,'selected'),'2026-10-01T12:00:00.000Z');
assert.equal(sourceRevisionDate(history,'missing'),null);
assert.equal(sourceRevisionDate({createdAt:'2026-10-15'},'selected'),null);
assert.equal(sourceRevisionDate([{microversionId:'selected',date:'invalid'}],'selected'),null);
assert.equal(sourceRevisionDate([{microversionId:'selected',created_at:'2026-10-15'}],'selected'),null);
