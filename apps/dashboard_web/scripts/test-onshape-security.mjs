import fs from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';
const source=fs.readFileSync('../../backend/supabase/functions/onshape-connector/security.ts','utf8');
const lib=await import('data:text/javascript;base64,'+Buffer.from(ts.transpileModule(source,{compilerOptions:{target:99,module:99}}).outputText).toString('base64'));
const id='b9b125099059ef4885429c29',ref='acdb00f42d2acd5937a2fd38',element='efe0a63c0d9576dea51ab012';
const link=`https://cad.onshape.com/documents/${id}/w/${ref}/e/${element}`;
assert.deepEqual(lib.parseSource(link),{documentId:id,referenceType:'w',referenceId:ref,elementId:element,configuration:'default'});
for(const bad of [link.replace('cad.onshape.com','evil.test'),link.replace('https:','http:'),link.replace('/w/','/x/'),'https://cad.onshape.com/documents',link.replace('cad.onshape.com','user:password@cad.onshape.com')])assert.throws(()=>lib.parseSource(bad));
const key=Buffer.from(crypto.getRandomValues(new Uint8Array(32))).toString('base64');
const envelope=await lib.seal({access_token:'secret-test',refresh_token:'refresh-test'},key,'connection-one');
assert.ok(!JSON.stringify(envelope).includes('secret-test'));
assert.equal((await lib.unseal(envelope,key,'connection-one')).access_token,'secret-test');
await assert.rejects(()=>lib.unseal(envelope,key,'connection-two'));
await assert.rejects(()=>lib.seal({},'bad','connection-one'));
let calls=0;
const read=lib.providerReader('test-secret',async(url,options)=>{calls++;assert.equal(url,'https://cad.onshape.com/api/documents?offset=0');assert.equal(options.redirect,'error');assert.equal(options.method,'GET');assert.equal(options.headers.Authorization,'Bearer test-secret');return Response.json({items:[]});});
await read('/documents?offset=0');
for(const path of ['https://evil.test','//evil.test','/users/sessioninfo','/documents/../users','/documents\\evil'])await assert.rejects(()=>read(path));
assert.equal(calls,1);
await assert.rejects(()=>lib.boundedJson(new Response('123456789'),4),e=>e.code==='SOURCE_TOO_LARGE');
await assert.rejects(()=>lib.boundedJson(new Response('private provider error',{status:401})),e=>e.code==='RECONNECT_REQUIRED'&&!e.message.includes('private'));
await assert.rejects(()=>lib.boundedJson(new Response('{}',{status:429})),e=>e.code==='RATE_LIMITED');
assert.equal((await lib.sha256('state')).length,64);
console.log('PASS: source identity, encrypted credential binding, redirect/host boundaries, bounded responses and sanitized provider errors');
