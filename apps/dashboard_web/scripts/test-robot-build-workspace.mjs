import fs from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';
const source=fs.readFileSync('src/lib/robotBuildWorkspace.ts','utf8');
const {buildView,selectBuild,readBuildPages}=await import('data:text/javascript;base64,'+Buffer.from(ts.transpileModule(source,{compilerOptions:{target:99,module:99}}).outputText).toString('base64'));
const projects=[{id:'one',status:'active'},{id:'two',status:'active'},{id:'old',status:'archived'},{id:'finished',status:'completed'}];
assert.equal(selectBuild(projects,new Set(['one']),null)?.id,'one');
assert.equal(selectBuild(projects,new Set(['one','two']),null),null);
assert.equal(selectBuild(projects,new Set(['old','finished']),null),null);
assert.equal(selectBuild(projects,new Set(['one']),'two')?.id,'two','explicit links beat implicit active build');
assert.equal(selectBuild(projects,new Set(['one']),'inaccessible'),null,'do not silently redirect unauthorized context');
assert.equal(selectBuild(projects,new Set(),'old')?.id,'old','history remains addressable');
assert.equal(buildView('assembly'),'assembly');assert.equal(buildView('unexpected'),'overview');
const rows=Array.from({length:1201},(_,id)=>({id}));
assert.deepEqual(await readBuildPages(async(a,z)=>({data:rows.slice(a,z+1),error:null})),rows);
await assert.rejects(readBuildPages(async()=>({data:[],error:Error('denied')})),/denied/);
await assert.rejects(readBuildPages(async()=>({data:null,error:null})),/Missing page/);
await assert.rejects(readBuildPages(async()=>({data:[1,2],error:null}),2,2),/exceeds/);
console.log('PASS build routing, explicit/denied/archive scope, pagination and fail-closed list completeness');
