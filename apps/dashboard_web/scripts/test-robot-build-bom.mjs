import fs from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';
const source=fs.readFileSync('../../backend/supabase/functions/onshape-connector/bom.ts','utf8');
const {structuralBom}=await import('data:text/javascript;base64,'+Buffer.from(ts.transpileModule(source,{compilerOptions:{target:99,module:99}}).outputText).toString('base64'));
const part=(id,extra={})=>({id,type:'Part',documentId:'doc',elementId:'element',documentMicroversion:'rev',partId:'plate',name:'Plate',...extra});
const run=(instances,subAssemblies=[],occurrences=[])=>structuralBom({assembly:{rootAssembly:{instances,occurrences},subAssemblies}},'ASSEMBLY');
let r=run([part('a'),part('b')]);
assert.equal(r.coverage,'resolved');assert.equal(r.rows[0].quantity,2);assert.equal(r.releaseEligible,false);
assert.equal(run([part('a'),part('b',{documentMicroversion:'new'})]).rows.length,2);
assert.equal(run([part('a'),part('b',{configuration:'size=large'})]).rows.length,2);
assert.equal(run([part('a'),part('b',{suppressed:true})]).rows[0].quantity,1);
const sub={documentId:'d',elementId:'e',documentMicroversion:'m',configuration:'',instances:[part('p')]};
const instance=id=>({id,type:'Assembly',documentId:'d',elementId:'e',documentMicroversion:'m',configuration:''});
r=run([instance('left'),instance('right')],[sub]);
assert.equal(r.rows[0].quantity,2);assert.deepEqual(r.rows[0].paths,[['left','p'],['right','p']]);
r=run([instance('left'),instance('right')],[sub],[{path:['left'],suppressed:true}]);assert.equal(r.rows[0].quantity,1);
r=run([instance('missing')]);assert.equal(r.coverage,'incomplete');assert.equal(r.issues[0].code,'UNRESOLVED_ASSEMBLY');
r=run([instance('cycle')],[{...sub,instances:[instance('again')]}]);assert.equal(r.coverage,'incomplete');assert.equal(r.issues[0].code,'ASSEMBLY_CYCLE');
assert.equal(run([part('a'),part('a')]).coverage,'incomplete');
assert.equal(run([part('a',{partId:undefined})]).coverage,'incomplete');
assert.equal(run([{id:'unknown',type:'Unknown'}]).coverage,'incomplete');
assert.equal(structuralBom({},'ASSEMBLY').coverage,'incomplete');
assert.equal(structuralBom({parts:[part('a')]},'PARTSTUDIO').coverage,'unsupported');
r=run(Array.from({length:1200},(_,i)=>part(String(i),{partId:'part'+i})));assert.equal(r.rows.length,1200);assert.equal(r.coverage,'resolved');
assert.equal(run([]).rows.length,0);
const assemblyEvidence={assembly:{rootAssembly:{instances:[instance('left'),instance('right')]},subAssemblies:[sub]}};
const purchased=structuralBom(assemblyEvidence,'ASSEMBLY',[['left'],['right']]);assert.equal(purchased.coverage,'resolved');assert.equal(purchased.rows.length,1);assert.equal(purchased.rows[0].quantity,2);assert.equal(purchased.rows[0].partId,'@assembly');
assert.equal(structuralBom(assemblyEvidence,'ASSEMBLY',[['missing']]).coverage,'incomplete');
assert.equal(structuralBom(assemblyEvidence,'ASSEMBLY',[['left'],['left','p']]).coverage,'incomplete','nested contradictory boundaries cannot silently disappear');
console.log('Robot Build structural BOM: nested/repeated/configured/suppressed/missing/cyclic/large/unsupported cases passed.');
